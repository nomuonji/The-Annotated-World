const piped=[
  'https://pipedapi.kavin.rocks','https://pipedapi.adminforge.de',
  'https://piped-api.garudalinux.org','https://pipedapi.r4fo.com'
];
const invidious=[
  'https://inv.nadeko.net','https://invidious.nerdvpn.de',
  'https://invidious.privacydev.net','https://yewtu.be'
];
const requests=[
  ...piped.map(root=>({origin:root,type:'piped',url:root+'/streams/'+id})),
  ...invidious.map(root=>({origin:root,type:'invidious',url:root+'/api/v1/videos/'+id}))
];
for (const r of requests) {
 try {
  const response=await fetch(r.url,{headers:{'Accept':'application/json','User-Agent':'Mozilla/5.0 (compatible; AnnotatedWorldSourceCheck/1.0)'},signal:AbortSignal.timeout(8500)});
  if(!response.ok){console.log('CAPTION_PROXY_STATUS',r.type,r.origin,response.status);continue}
  const data=await response.json();
  const tracks=r.type==='piped'?data.subtitles:data.captions;
  const arr=Array.isArray(tracks)?tracks:[];
  // never print subtitle contents, signed URLs or provider tokens.
  console.log('CAPTION_PROXY_RESULT',JSON.stringify({
   type:r.type,origin:r.origin,videoTitle:String(data.title||'').slice(0,110),
   duration:data.duration||data.lengthSeconds||null,tracks:arr.slice(0,8).map(x=>({
    lang:x.code||x.languageCode||x.language||x.label||null,
    autoGenerated:x.autoGenerated??x.auto??null,
    sourcePath:(()=>{try{let u=new URL(x.url);return u.pathname.includes('/api/timedtext')?'youtube-timedtext-relay':'unidentified'}catch{return 'unknown'}})()
   })),count:arr.length
  }));
 }catch(e){console.log('CAPTION_PROXY_FAILED',r.type,r.origin,String(e.message||e).slice(0,80))}
}
